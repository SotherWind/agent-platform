function padParagraph(text, targetLen) {
  const filler =
    "本条款适用于集团及境内全资子公司，境外子公司可参照执行并遵守当地法律。" +
    "未尽事宜由主管部门负责解释，修订版本以 OA 公告为准。" +
    "员工有义务熟悉并遵守本章规定，违反者按员工手册纪律条款处理。";
  let out = text;
  while (out.length < targetLen) {
    out += filler;
  }
  return out;
}

function renderSection(part, section, index) {
  const body = section.facts
    .map((f, i) => `${i + 1}. ${f}`)
    .join("\n\n");
  const appendix = [
    `本章属于《集团企业管理手册》${part}，条款编号 ${part.slice(0, 4)}-${String(index + 1).padStart(2, "0")}。`,
    "执行过程中如有疑问，请联系对口职能部门或提交 ITSM/HR 工单咨询。",
    "历史版本变更记录可在文档管理系统查阅，以最新发布版本为准。",
    "培训材料与 FAQ 见内网知识库，新员工入职培训须覆盖本章核心条款。",
  ].join("\n\n");

  return `## ${section.title}\n\n${padParagraph(body + "\n\n" + appendix, 1400)}`;
}

